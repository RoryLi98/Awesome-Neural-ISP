"""Generate README.md, WEIGHTS.md and docs/index.html from the YAML files in data/.

    python scripts/build.py          # validate and write the generated files
    python scripts/build.py --check  # validate and fail if the generated files are out of date (used in CI)
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from urllib.parse import quote

import isp_data
from isp_data import ROOT, STATUSES, WEIGHT_STATUSES

GENERATED = '<!-- Generated by scripts/build.py from data/*.yaml. Edit the YAML files, not this file. -->'
RANK = {'weights': 0, 'weights-in-repo': 0, 'code': 1, 'unofficial': 1, 'coming-soon': 2, 'no-code': 2}
TOOL_KINDS = [('raw', 'RAW I/O'), ('isp', 'Classical ISP Pipelines & Algorithms'),
              ('learned', 'Learned-ISP Toolboxes'), ('editor', 'RAW Developers')]


# ---------------------------------------------------------------- helpers
def slug(text: str) -> str:
    """GitHub's heading anchor: lowercase, drop punctuation, spaces to hyphens."""
    s = text.strip().lower()
    s = re.sub(r'[^\w\- ]', '', s)
    return s.replace(' ', '-')


def md(text) -> str:
    """Escape text for use inside a Markdown table cell."""
    s = str(text or '')
    s = s.replace('\\', '\\\\').replace('|', '\\|').replace('*', '\\*').replace('<', '&lt;').replace('>', '&gt;')
    return re.sub(r'\s+', ' ', s).strip()


def link(label, url) -> str:
    return f'[{md(label)}]({url})'


def badge(label, value, color, target):
    lab = quote(label.replace('-', '--').replace('_', '__'))
    val = quote(str(value).replace('-', '--').replace('_', '__'))
    return f'[![{label}](https://img.shields.io/badge/{lab}-{val}-{color})]({target})'


def sort_papers(ps):
    return sorted(ps, key=lambda p: (RANK[p['status']], -p['year'], p['name'].lower()))


def code_cell(p) -> str:
    st, url = p['status'], p.get('code')
    if not url:
        return 'coming soon' if st == 'coming-soon' else '—'
    host = 'GitHub' if 'github.com' in url else 'code'
    label = {'unofficial': f'{host} (unofficial)', 'coming-soon': f'{host} (coming soon)'}.get(st, host)
    out = link(label, url)
    if p.get('framework'):
        out += f"<br><sub>{md(p['framework'])}</sub>"
    return out


def paper_cell(p) -> str:
    out = f"**{link(p['name'], p['paper'])}**"
    if p['title'].strip().lower() != p['name'].strip().lower():
        out += f"<br>{md(p['title'])}"
    sub = md(p['tldr'])
    if p.get('note'):
        sub += f" <i>Note: {md(p['note'])}</i>"
    return out + f'<br><sub>{sub}</sub>'


def weights_cell(p) -> str:
    return '<br>'.join(link(w['label'], w['url']) for w in p.get('weights') or [])


def stats(d):
    ps = [p for _, p in isp_data.all_papers(d)]
    return dict(n=len(ps),
                code=sum(p['status'] in ('weights', 'weights-in-repo', 'code', 'unofficial') for p in ps),
                weights=sum(p['status'] in WEIGHT_STATUSES for p in ps),
                datasets=len(d['datasets']))


