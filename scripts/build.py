# ---------------------------------------------------------------- WEIGHTS.md
def weights_md(d) -> str:
    cfg, s = d['config'], stats(d)
    L = [GENERATED, '', '# Pretrained Weights Index', '',
         f"All {s['weights']} papers in [{cfg['title']}](README.md) that release pretrained weights, grouped by topic. "
         f"Links are copied from each repository README (checked {cfg['checked']}); \"in repo\" means the checkpoint is "
         'committed to the repository.', '']
    for c in d['categories']:
        ps = [p for p in sort_papers(d['papers'][c['id']]) if p['status'] in WEIGHT_STATUSES]
        if not ps:
            continue
        L += [f"## {c['title']}", '', '| Model | Venue | Weights | Code | Framework |', '|:--|:--|:--|:--|:--|']
        for p in ps:
            note = f"<br><sub>{md(p['note'])}</sub>" if p.get('note') else ''
            L.append(f"| **{link(p['name'], p['paper'])}**{note} | {md(p['venue'])} {p['year']} | {weights_cell(p)} | "
                     f"{link('GitHub' if 'github.com' in (p.get('code') or '') else 'code', p['code']) if p.get('code') else '—'} | "
                     f"{md(p.get('framework') or '—')} |")
        L.append('')
    return '\n'.join(L)


# ---------------------------------------------------------------- docs/index.html
SITE_ST = {'weights': 'W', 'weights-in-repo': 'R', 'code': 'C', 'unofficial': 'U', 'coming-soon': 'S', 'no-code': 'N'}


def site(d) -> str:
    cfg, s = d['config'], stats(d)
    P = [dict(n=p['name'], t=p['title'], v=p['venue'], y=p['year'], c=c['id'], s=p['tldr'], p=p['paper'],
              g=p.get('code') or '', st=SITE_ST[p['status']], w=[[w['label'], w['url']] for w in p.get('weights') or []],
              note=p.get('note') or '', fw=p.get('framework') or '') for c, p in isp_data.all_papers(d)]
    D = [[x['name'], x['year'], x.get('source') or '', x.get('capture') or '', x.get('size') or '', x['url'], x['use']]
         for x in d['datasets']]
    CATS = [dict(k=c['id'], name=c['title'], short=c['short'], desc=c['description']) for c in d['categories']]
    TR = [[t['title'], t['text'], t['examples']] for t in d['trends']]
    TOOLS = [[t['name'], t['url'], t['description'], t.get('language') or '', dict(TOOL_KINDS).get(t.get('kind', 'isp'))]
             for t in d['tools']]
    years = [p['y'] for p in P]
    js = lambda x: json.dumps(x, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/')
    tpl = (ROOT / 'scripts' / 'site_template.html').read_text(encoding='utf-8')
    rep = {'__P__': js(P), '__D__': js(D), '__CATS__': js(CATS), '__TRENDS__': js(TR), '__TOOLS__': js(TOOLS),
           '__NP__': str(s['n']), '__NCODE__': str(s['code']), '__NW__': str(s['weights']), '__ND__': str(s['datasets']),
           '__CHECKED__': cfg['checked'], '__TITLE__': cfg['title'], '__TAGLINE__': cfg['tagline'],
           '__REPO_URL__': f"https://github.com/{cfg['owner']}/{cfg['repo']}", '__Y0__': str(min(years)), '__Y1__': str(max(years))}
    for k, v in rep.items():
        tpl = tpl.replace(k, v)
    return tpl


# ---------------------------------------------------------------- main
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true', help='fail if generated files are out of date')
    args = ap.parse_args()
    d = isp_data.load()
    errs = isp_data.validate(d)
    if errs:
        print('Data validation failed:\n  ' + '\n  '.join(errs))
        sys.exit(1)
    outputs = {ROOT / 'README.md': readme(d), ROOT / 'WEIGHTS.md': weights_md(d), ROOT / 'docs' / 'index.html': site(d)}
    stale = []
    for path, text in outputs.items():
        old = path.read_text(encoding='utf-8') if path.exists() else None
        if args.check:
            if old != text:
                stale.append(str(path.relative_to(ROOT)))
        elif old != text:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding='utf-8')
            print('wrote', path.relative_to(ROOT))
    if stale:
        print('Out of date (run `python scripts/build.py` and commit):', ', '.join(stale))
        sys.exit(1)
    s = stats(d)
    print(f"ok: {s['n']} papers, {s['code']} with code, {s['weights']} with weights, {s['datasets']} datasets")


if __name__ == '__main__':
    main()
